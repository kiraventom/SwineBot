namespace SwineBot.Model;

/// <summary>
/// Числа роста свина от забоёв.
///
/// Множитель — это не вечный пассивный доход, а разгон: он копится в «запасе»
/// (<see cref="Swine.MultiplierFuel"/>), пока свин лёгкий, и тратится по шагу за каждую
/// кормёжку, когда свин забрался выше <see cref="EliteThresholdShare"/> от веса лидера
/// беседы. Так он помогает вырваться с низов и не даёт бесконечно ехать на старых забоях.
///
/// Бонус к порции суб-линейный (корень), иначе убийца уходил в неубиваемый отрыв:
/// при Σ = 17 000 кг линейная формула давала 4.41 против 1.14 у бережливого.
/// </summary>
public static class GrowthBalance
{
    /// <summary>Растёт ли бонус суб-линейно (корень) или линейно (старое поведение).</summary>
    public static bool SubLinear { get; set; } = true;

    /// <summary>
    /// Бонус за корень из забитых килограммов (суб-линейная модель).
    ///
    /// 0.03 подобран под цель «забил X — вырос до X»: банк 10 000 кг даёт множитель 4.00,
    /// который выгорает примерно за полгода, оставляя свина на ~11 100 кг (см. §8
    /// в GROWTH-MULTIPLIER.md).
    /// </summary>
    public static double PerSqrtKg { get; set; } = 0.03;

    /// <summary>Бонус за килограмм (линейная модель, оставлена для сравнения).</summary>
    public const double PerKg = 0.0002;

    /// <summary>Ниже этого множитель не опускается: базовый рост есть у всех.</summary>
    public const double MinMultiplier = 1.0;

    /// <summary>
    /// Доля веса лидера беседы, с которой начинается трата запаса: 0.75 — три четверти
    /// веса самого толстого свина. Ниже порога множитель не тратится вообще.
    ///
    /// Это осознанное решение: множитель — разгон для того, кто лезет с низов, и налог
    /// для того, кто уже наверху. Поэтому правило «забил X — вырос до X» считается именно
    /// для цикла убийцы (свой забой → 1 кг → разгон): если горение начинается с веса
    /// на пороге, а не с единицы, в итог добавляется этот стартовый вес и обычный рост
    /// за время горения (см. GROWTH-MULTIPLIER.md §8.3).
    /// </summary>
    public static double EliteThresholdShare { get; set; } = 0.75;

    /// <summary>
    /// Сколько запаса тратится на один килограмм бонусной массы.
    ///
    /// Именно так, а не «долей излишка за кормёжку»: при трате, привязанной к полученной
    /// массе, суммарный бонус за весь разгон становится предсказуемым — при 1.0 свин
    /// выменивает ровно столько, сколько забил. При 1.5 на килограмм бонуса уходит
    /// полтора килограмма забитого, и банк 10 000 даёт около 6 700 кг бонусной массы,
    /// а остальное до обычного роста добирает кормёжка — в сумме те самые ~10–11 тыс.
    ///
    /// Замер (модель + сценарии): банк 10 000 при горении с 1 кг и кормёжке в темпе Ганса
    /// даёт 11 078 кг за ~6 месяцев.
    /// </summary>
    public static double FuelPerBonusKg { get; set; } = 1.5;

    /// <summary>Множитель, который даёт накопленный запас.</summary>
    public static double ModifierFor(double fuel)
    {
        var clamped = Math.Max(0, fuel);
        var bonus = SubLinear ? PerSqrtKg * Math.Sqrt(clamped) : PerKg * clamped;
        return 1 + bonus;
    }

    /// <summary>Обратная операция: сколько запаса соответствует множителю.</summary>
    public static double FuelForModifier(double modifier)
    {
        var bonus = Math.Max(0, modifier - 1);
        return SubLinear ? Math.Pow(bonus / PerSqrtKg, 2) : bonus / PerKg;
    }

    /// <summary>
    /// Сколько запаса съедает кормёжка с бонусной массой <paramref name="bonusKg"/>.
    /// Заодно это и есть механика «X в X»: сумма бонусной массы за разгон ≈ банк / FuelPerBonusKg.
    /// </summary>
    public static double FuelSpentForBonus(double bonusKg)
        => Math.Max(0, bonusKg) * FuelPerBonusKg;
}
