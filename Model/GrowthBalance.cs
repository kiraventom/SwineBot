namespace SwineBot.Model;

/// <summary>
/// Числа роста свина от забоёв. Ключевое решение (см. DUELS-V3-DESIGN.md §7):
/// бонус к кормёжке растёт **суб-линейно** от суммарно забитого веса.
///
/// Линейный рост (`1 + 0.0002·Σ`) превращал убийцу в паровоз: при Σ = 17 000 кг
/// множитель 4.41 против 1.14 у бережливого, и никакие дуэли этого не компенсируют.
/// Корень даёт тому же убийце ~2.30 при том же Σ: забой всё ещё выгоден, но не
/// превращается в бесконечный отрыв. Коэффициент подобран свипом (l20): 0.008 → разрыв
/// +3 188, 0.010 → +8, 0.012 → +1 641, поэтому 0.010.
/// </summary>
public static class GrowthBalance
{
    /// <summary>Растёт ли бонус суб-линейно (корень) или линейно (старое поведение).</summary>
    public static bool SubLinear { get; set; } = true;

    /// <summary>Бонус за корень из забитых килограммов (суб-линейная модель).</summary>
    public static double PerSqrtKg { get; set; } = 0.010;

    /// <summary>Бонус за килограмм (линейная модель, оставлена для сравнения).</summary>
    public const double PerKg = 0.0002;
}
